//! Rust wasm-bindgen shim generator.
//!
//! Covers (Path A contract v1):
//!
//! - Scalars, bool, String, Vec<u8>, Option<T>, Vec<T>
//! - Records / enums via **explicit lowering/lifting**. The shim emits a
//!   `__lower_<name>` / `__lift_<name>` helper for every record and
//!   non-error enum. Lowering reads fields via `js_sys::Reflect::get`;
//!   lifting builds a fresh `js_sys::Object` / string / array. There is
//!   no `serde` or `serde_wasm_bindgen` anywhere in the wasm link — not
//!   on the downstream core crate, not in the generated shim, and not
//!   in the auto-generated wasm host crate.
//! - Error enums still propagate via `JsError::new(&format!("{e:?}"))`
//!   because they only cross the boundary as exceptions, never as value
//!   returns or arguments.
//! - Opaque objects (struct + trait-interface) via per-object thread-local
//!   registry. Constructors returning `Self` or `Arc<Self>` both work via
//!   the `__Coerce` autoref-specialisation trick.
//! - Free functions taking or returning object handles.
//! - Callback interfaces / `with_foreign` traits: the JS object is
//!   registered in the runtime callback map, its handle is lowered as a
//!   `u32`, and the shim wraps it in a generated `__Js<Name>` struct that
//!   implements the biz trait by dispatching back to JS via a pair of
//!   `thread_local!`-stored `js_sys::Function`s. `Drop` releases the JS
//!   registry slot.
//!
//! Anything still unsupported (Map/Set) is emitted as a stub
//! that throws `JsError` at runtime — never a silent skip. Timestamp
//! and duration are covered with explicit `Date` / millisecond
//! lowering and lifting.

use std::fmt::Write;

use heck::ToSnakeCase;
use uniffi_bindgen::interface::{
    AsType, ComponentInterface, Constructor, Enum, Function, Method, Object, ObjectImpl, Record,
    Type,
};

pub fn render_wasm_rust(ci: &ComponentInterface) -> String {
    let crate_ident = ci.crate_name().replace('-', "_");
    let mut out = String::new();
    writeln!(
        out,
        "// AUTOGENERATED by uniffi_bindgen_javascript (wasm flavor)."
    )
    .unwrap();
    writeln!(
        out,
        "// Do not edit by hand; regenerate via uniffi-bindgen."
    )
    .unwrap();
    writeln!(out, "//").unwrap();
    writeln!(
        out,
        "// wasm-bindgen shim for the `{}` namespace.",
        ci.namespace()
    )
    .unwrap();
    writeln!(out).unwrap();
    // NB: no inner `#![allow(...)]` — this file is consumed via
    // `include!()` from the auto-generated host crate, and inner
    // attributes aren't permitted inside an `include!` expansion.
    writeln!(
        out,
        "#[allow(unused_imports)] use wasm_bindgen::prelude::*;"
    )
    .unwrap();
    writeln!(out, "#[allow(unused_imports)] use wasm_bindgen::JsCast;").unwrap();
    writeln!(
        out,
        "#[allow(unused_imports)] use std::collections::HashMap;"
    )
    .unwrap();
    writeln!(out, "#[allow(unused_imports)] use std::sync::Arc;").unwrap();
    writeln!(
        out,
        "#[allow(unused_imports)] use std::cell::{{Cell, RefCell}};"
    )
    .unwrap();
    writeln!(out).unwrap();

    let has_objects = ci
        .object_definitions()
        .iter()
        .any(|o| !matches!(o.imp(), ObjectImpl::CallbackTrait));
    let has_cb_objects = ci
        .object_definitions()
        .iter()
        .any(|o| matches!(o.imp(), ObjectImpl::CallbackTrait));
    let has_cb_ifaces = !ci.callback_interface_definitions().is_empty();
    let has_callbacks = has_cb_objects || has_cb_ifaces;

    // Emit explicit `__lower_<name>` / `__lift_<name>` helpers for
    // every record and non-error enum.
    emit_value_helpers(&mut out, ci, &crate_ident);
    emit_temporal_helpers(&mut out);

    if has_objects {
        emit_object_helpers(&mut out);
    }
    if has_callbacks {
        emit_callback_helpers(&mut out);
    }

    // Registries + shims for opaque objects (struct / trait-interface).
    for obj in ci.object_definitions() {
        if matches!(obj.imp(), ObjectImpl::CallbackTrait) {
            continue;
        }
        render_object(&mut out, &crate_ident, obj);
        writeln!(out).unwrap();
    }

    // `__Js<Name>` wrappers for each callback trait.
    for cbi in ci.callback_interface_definitions() {
        render_callback_wrapper(
            &mut out,
            &crate_ident,
            cbi.name(),
            &cbi.methods()
                .iter()
                .map(|m| (*m).clone())
                .collect::<Vec<_>>(),
        );
    }
    for obj in ci.object_definitions() {
        if !matches!(obj.imp(), ObjectImpl::CallbackTrait) {
            continue;
        }
        render_callback_wrapper(
            &mut out,
            &crate_ident,
            obj.name(),
            obj.methods()
                .into_iter()
                .cloned()
                .collect::<Vec<_>>()
                .as_slice(),
        );
    }

    // Value-type constructors/methods for records and non-error enums.
    for record in ci.record_definitions() {
        for constructor in record.constructors() {
            render_value_constructor(
                &mut out,
                &crate_ident,
                record.name(),
                &record.as_type(),
                constructor,
            );
            writeln!(out).unwrap();
        }
        for method in record.methods() {
            render_value_method(
                &mut out,
                &crate_ident,
                record.name(),
                &record.as_type(),
                method,
            );
            writeln!(out).unwrap();
        }
    }
    for enum_ in ci.enum_definitions() {
        if ci.is_name_used_as_error(enum_.name()) {
            continue;
        }
        for constructor in enum_.constructors() {
            render_value_constructor(
                &mut out,
                &crate_ident,
                enum_.name(),
                &enum_.as_type(),
                constructor,
            );
            writeln!(out).unwrap();
        }
        for method in enum_.methods() {
            render_value_method(
                &mut out,
                &crate_ident,
                enum_.name(),
                &enum_.as_type(),
                method,
            );
            writeln!(out).unwrap();
        }
    }

    // Free functions.
    for f in ci.function_definitions() {
        render_function(&mut out, &crate_ident, &f);
        writeln!(out).unwrap();
    }
    out
}

