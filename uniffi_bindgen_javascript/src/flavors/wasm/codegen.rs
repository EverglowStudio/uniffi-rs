/// Emit `struct __Js<Name>` implementing the biz-side trait by dispatching
/// through the thread-local `__uniffi_cb_invoke` helper. This lets Rust
/// transparently call back into a foreign JS object.
fn render_callback_wrapper(out: &mut String, crate_ident: &str, name: &str, methods: &[Method]) {
    writeln!(out, "// --- callback wrapper for `{name}` ---").unwrap();
    writeln!(out, "struct __Js{name} {{ handle: u32 }}").unwrap();
    writeln!(out, "impl Drop for __Js{name} {{").unwrap();
    writeln!(
        out,
        "    fn drop(&mut self) {{ __uniffi_cb_release(self.handle); }}"
    )
    .unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "impl ::{crate_ident}::{name} for __Js{name} {{").unwrap();
    for m in methods {
        let m_name = m.name();
        let arg_info: Vec<(String, Lowering)> = m
            .arguments()
            .iter()
            .map(|a| (a.name().to_string(), classify(&a.as_type(), crate_ident)))
            .collect();
        // Build the biz-facing Rust signature. We take the args by value so
        // the `impl Trait for __Js<Name>` matches a simple `fn m(&self, a: T)`.
        let rust_args = arg_info
            .iter()
            .map(|(n, l)| {
                let t = match l {
                    Lowering::Native(t) => t.clone(),
                    Lowering::Value { core_ty, .. } => core_ty.clone(),
                    Lowering::Object { rust_ty, .. } => format!("Arc<{rust_ty}>"),
                    Lowering::Callback { rust_ty, .. } => format!("Arc<{rust_ty}>"),
                    Lowering::Unsupported(_) => "JsValue".to_string(),
                };
                format!("{n}: {t}")
            })
            .collect::<Vec<_>>()
            .join(", ");
        let ret_info = m.return_type().map(|t| classify(t, crate_ident));
        let ret_ty = match &ret_info {
            Some(Lowering::Native(s)) => s.clone(),
            Some(Lowering::Value { core_ty, .. }) => core_ty.clone(),
            _ => "()".to_string(),
        };
        writeln!(
            out,
            "    fn {m_name}(&self{}{rust_args}) -> {ret_ty} {{",
            if rust_args.is_empty() { "" } else { ", " }
        )
        .unwrap();
        // Build a JS args array via explicit lift_expr — no serde.
        writeln!(out, "        let __args_arr = ::js_sys::Array::new();").unwrap();
        for (arg, (n, l)) in m.arguments().iter().zip(arg_info.iter()) {
            match l {
                Lowering::Native(_) | Lowering::Value { .. } => {
                    let ty = arg.as_type();
                    let lift = lift_expr(n, &ty, 0);
                    writeln!(out, "        let __lifted_{n} = {lift};").unwrap();
                    writeln!(out, "        let _ = __args_arr.push(&__lifted_{n});").unwrap();
                }
                _ => {
                    writeln!(out, "        let _ = __args_arr.push(&JsValue::NULL);").unwrap();
                }
            }
        }
        writeln!(out, "        let __args: JsValue = __args_arr.into();").unwrap();
        writeln!(
            out,
            "        let __ret = __uniffi_cb_invoke(self.handle, \"{}\", __args);",
            lower_camel(m_name)
        )
        .unwrap();
        // Lift return via explicit lower_expr — no serde.
        match &ret_info {
            Some(Lowering::Native(_)) | Some(Lowering::Value { .. }) => {
                let ty = m
                    .return_type()
                    .expect("ret_info Some implies return_type")
                    .clone();
                let lower = lower_expr("__ret", &ty, 0);
                writeln!(
                    out,
                    "        ({lower}).unwrap_or_else(|e| panic!(\"uniffi wasm callback bad return: {{e:?}}\"))"
                )
                .unwrap();
            }
            Some(_) | None => {
                writeln!(out, "        let _ = __ret;").unwrap();
            }
        }
        writeln!(out, "    }}").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn lower_camel(rust: &str) -> String {
    // tiny local snake→lowerCamel, since heck isn't imported here for it
    // and we only need the same mapping the api_module uses.
    use heck::ToLowerCamelCase;
    rust.to_lower_camel_case()
}

