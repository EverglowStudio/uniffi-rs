/// Emitted once when any struct/trait object is present.
fn emit_object_helpers(out: &mut String) {
    // Autoref-specialisation trick: the inherent impl on `__Coerce<Arc<T>>`
    // wins over the blanket trait impl on `__Coerce<T>`, so the same
    // `__Coerce(x).__into_arc()` call site handles both `-> Self` and
    // `-> Arc<Self>` constructor shapes with no codegen-side branching.
    writeln!(
        out,
        "struct __Coerce<T>(T);\n\
         impl<T: ?Sized> __Coerce<Arc<T>> {{ #[inline] fn __into_arc(self) -> Arc<T> {{ self.0 }} }}\n\
         trait __CoerceFallback<T> {{ fn __into_arc(self) -> Arc<T>; }}\n\
         impl<T> __CoerceFallback<T> for __Coerce<T> {{ #[inline] fn __into_arc(self) -> Arc<T> {{ Arc::new(self.0) }} }}"
    )
    .unwrap();
    writeln!(out).unwrap();
}

/// Emitted once when any callback-trait / `callback interface` is present.
/// Provides the thread-local `js_sys::Function` slots that the generated
/// `__Js<Name>` trait impls dispatch through, plus the `#[wasm_bindgen]`
/// setter that `backend-wasm.ts` calls during `initBackend()`.
fn emit_callback_helpers(out: &mut String) {
    writeln!(
        out,
        r#"thread_local! {{
    static __UNIFFI_CB_INVOKE: RefCell<Option<::js_sys::Function>> = RefCell::new(None);
    static __UNIFFI_CB_RELEASE: RefCell<Option<::js_sys::Function>> = RefCell::new(None);
}}

#[wasm_bindgen]
pub fn __uniffi_set_cb_invoker(invoke: ::js_sys::Function, release: ::js_sys::Function) {{
    __UNIFFI_CB_INVOKE.with(|c| *c.borrow_mut() = Some(invoke));
    __UNIFFI_CB_RELEASE.with(|c| *c.borrow_mut() = Some(release));
}}

fn __uniffi_cb_invoke(handle: u32, method: &str, args: JsValue) -> JsValue {{
    __UNIFFI_CB_INVOKE.with(|c| {{
        let b = c.borrow();
        let f = b.as_ref().expect("uniffi: callback invoker not installed");
        f.call3(
            &JsValue::NULL,
            &JsValue::from_f64(handle as f64),
            &JsValue::from_str(method),
            &args,
        )
        .unwrap_or(JsValue::NULL)
    }})
}}

fn __uniffi_cb_release(handle: u32) {{
    __UNIFFI_CB_RELEASE.with(|c| {{
        if let Some(f) = c.borrow().as_ref() {{
            let _ = f.call1(&JsValue::NULL, &JsValue::from_f64(handle as f64));
        }}
    }});
}}
"#
    )
    .unwrap();
    writeln!(out).unwrap();
}

/// Emitted once for timestamp/duration lowering/lifting. Keeps
/// chronological conversions explicit and serde-free.
fn emit_temporal_helpers(out: &mut String) {
    out.push_str(
        r#"#[allow(dead_code)]
fn __uniffi_lower_timestamp(__js: JsValue) -> Result<::std::time::SystemTime, JsError> {
    let __date: ::js_sys::Date = __js.dyn_into().map_err(|_| JsError::new("expected Date"))?;
    let __ms = __date.get_time();
    if !__ms.is_finite() {
        return Err(JsError::new("invalid Date"));
    }
    if __ms.abs() > 8.64e15 {
        return Err(JsError::new("timestamp exceeds JS Date range"));
    }
    let __ms_i = __ms.trunc() as i64;
    if __ms_i >= 0 {
        ::std::time::UNIX_EPOCH
            .checked_add(::std::time::Duration::from_millis(__ms_i as u64))
            .ok_or_else(|| JsError::new("timestamp overflow"))
    } else {
        ::std::time::UNIX_EPOCH
            .checked_sub(::std::time::Duration::from_millis((-__ms_i) as u64))
            .ok_or_else(|| JsError::new("timestamp overflow"))
    }
}

#[allow(dead_code)]
fn __uniffi_lift_timestamp(__ts: ::std::time::SystemTime) -> Result<JsValue, JsError> {
    let __ms = match __ts.duration_since(::std::time::UNIX_EPOCH) {
        Ok(__delta) => {
            (__delta.as_secs() as f64) * 1000.0 + (__delta.subsec_nanos() as f64) / 1_000_000.0
        }
        Err(__err) => {
            let __delta = __err.duration();
            -((__delta.as_secs() as f64) * 1000.0 + (__delta.subsec_nanos() as f64) / 1_000_000.0)
        }
    };
    if !__ms.is_finite() || __ms.abs() > 8.64e15 {
        return Err(JsError::new("timestamp exceeds JS Date range"));
    }
    Ok::<JsValue, JsError>(::js_sys::Date::new(&JsValue::from_f64(__ms)).into())
}

#[allow(dead_code)]
fn __uniffi_lower_duration(__js: JsValue) -> Result<::std::time::Duration, JsError> {
    let __ms = __js
        .as_f64()
        .ok_or_else(|| JsError::new("expected duration milliseconds number"))?;
    if !__ms.is_finite() {
        return Err(JsError::new("duration must be finite"));
    }
    if __ms < 0.0 {
        return Err(JsError::new("duration must be non-negative"));
    }
    let __secs_f = (__ms / 1000.0).trunc();
    if __secs_f > u64::MAX as f64 {
        return Err(JsError::new("duration exceeds Rust range"));
    }
    let mut __secs = __secs_f as u64;
    let mut __nanos = ((__ms % 1000.0) * 1_000_000.0).round() as u32;
    if __nanos == 1_000_000_000 {
        __nanos = 0;
        __secs = __secs
            .checked_add(1)
            .ok_or_else(|| JsError::new("duration exceeds Rust range"))?;
    }
    Ok::<::std::time::Duration, JsError>(::std::time::Duration::new(__secs, __nanos))
}

#[allow(dead_code)]
fn __uniffi_lift_duration(__dur: ::std::time::Duration) -> Result<JsValue, JsError> {
    let __ms = (__dur.as_secs() as f64) * 1000.0 + (__dur.subsec_nanos() as f64) / 1_000_000.0;
    if !__ms.is_finite() {
        return Err(JsError::new("duration exceeds JS number range"));
    }
    Ok::<JsValue, JsError>(JsValue::from_f64(__ms))
}
"#,
    );
    writeln!(out).unwrap();
}

