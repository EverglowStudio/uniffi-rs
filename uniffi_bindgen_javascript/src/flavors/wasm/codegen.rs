fn rust_ty_for_object(crate_ident: &str, obj: &Object) -> String {
    match obj.imp() {
        ObjectImpl::Struct => format!("::{crate_ident}::{}", obj.name()),
        ObjectImpl::Trait => format!("dyn ::{crate_ident}::{}", obj.name()),
        ObjectImpl::CallbackTrait => format!("dyn ::{crate_ident}::{}", obj.name()),
    }
}

fn rust_ty_for_type(crate_ident: &str, ty: &Type) -> String {
    match ty {
        Type::Object { name, imp, .. } => match imp {
            ObjectImpl::Struct => format!("::{crate_ident}::{name}"),
            _ => format!("dyn ::{crate_ident}::{name}"),
        },
        Type::CallbackInterface { name, .. } => format!("dyn ::{crate_ident}::{name}"),
        _ => unreachable!(),
    }
}

fn render_object(out: &mut String, crate_ident: &str, obj: &Object) {
    let name = obj.name();
    let snake = name.to_snake_case();
    let rust_ty = rust_ty_for_object(crate_ident, obj);
    let reg = format!("__{}_REG", snake.to_uppercase());
    let next = format!("__{}_NEXT", snake.to_uppercase());

    writeln!(out, "// --- object `{name}` ---").unwrap();
    writeln!(out, "thread_local! {{").unwrap();
    writeln!(
        out,
        "    static {reg}: RefCell<HashMap<u32, Arc<{rust_ty}>>> = RefCell::new(HashMap::new());"
    )
    .unwrap();
    writeln!(out, "    static {next}: Cell<u32> = Cell::new(0);").unwrap();
    writeln!(out, "}}").unwrap();

    // Helper names use the `__uniffi_` prefix so they can never collide
    // with an exported method shim (e.g. an object method called `get`
    // would otherwise clash with the registry `counter_get` lookup).
    writeln!(
        out,
        "fn __uniffi_{snake}_insert(obj: Arc<{rust_ty}>) -> u32 {{\n    \
         let id = {next}.with(|c| {{ let n = c.get() + 1; c.set(n); n }});\n    \
         {reg}.with(|r| {{ r.borrow_mut().insert(id, obj); }});\n    \
         id\n\
         }}"
    )
    .unwrap();
    writeln!(
        out,
        "fn __uniffi_{snake}_get(handle: u32) -> Result<Arc<{rust_ty}>, JsError> {{\n    \
         {reg}.with(|r| r.borrow().get(&handle).cloned()\n        \
         .ok_or_else(|| JsError::new(&format!(\"invalid handle for `{name}`: {{}}\", handle))))\n\
         }}"
    )
    .unwrap();

    writeln!(out, "#[wasm_bindgen]").unwrap();
    writeln!(
        out,
        "pub fn __uniffi_{snake}_object_free(handle: u32) {{\n    \
         {reg}.with(|r| {{ r.borrow_mut().remove(&handle); }});\n\
         }}"
    )
    .unwrap();

    for c in obj.constructors() {
        render_constructor(out, crate_ident, &snake, &rust_ty, c);
    }
    for m in obj.methods() {
        render_method(out, crate_ident, &snake, m);
    }
}

fn render_constructor(
    out: &mut String,
    crate_ident: &str,
    snake: &str,
    rust_ty: &str,
    c: &Constructor,
) {
    let fn_name = format!("{snake}_{}", c.name().to_snake_case());
    let arg_info: Vec<(String, Lowering)> = c
        .arguments()
        .iter()
        .map(|a| (a.name().to_string(), classify(&a.as_type(), crate_ident)))
        .collect();
    let is_async = c.is_async();
    let throws = c.throws_type().is_some();

    if arg_info
        .iter()
        .any(|(_, l)| matches!(l, Lowering::Unsupported(_)))
    {
        writeln!(out, "#[wasm_bindgen]").unwrap();
        writeln!(
            out,
            "pub fn {fn_name}() -> Result<u32, JsError> {{\n    \
             Err(JsError::new(\"constructor has unsupported argument types\"))\n\
             }}"
        )
        .unwrap();
        return;
    }

    let params = param_list(&arg_info);
    let async_kw = if is_async { "async " } else { "" };
    let call_await = if is_async { ".await" } else { "" };

    writeln!(out, "#[wasm_bindgen]").unwrap();
    writeln!(
        out,
        "pub {async_kw}fn {fn_name}({params}) -> Result<u32, JsError> {{"
    )
    .unwrap();
    emit_arg_decoders(out, &arg_info);
    let pass = arg_pass(&arg_info);
    let call = format!("<{rust_ty}>::{}({pass}){call_await}", c.name());
    let obj_expr = if throws {
        format!("{call}.map_err(|e| JsError::new(&format!(\"{{e:?}}\")))?")
    } else {
        call
    };
    writeln!(
        out,
        "    let __obj: Arc<_> = __Coerce({obj_expr}).__into_arc();"
    )
    .unwrap();
    writeln!(
        out,
        "    Ok::<u32, JsError>(__uniffi_{snake}_insert(__obj))"
    )
    .unwrap();
    writeln!(out, "}}").unwrap();
}

fn render_method(out: &mut String, crate_ident: &str, snake: &str, m: &Method) {
    let fn_name = format!("{snake}_{}", m.name().to_snake_case());
    let arg_info: Vec<(String, Lowering)> = m
        .arguments()
        .iter()
        .map(|a| (a.name().to_string(), classify(&a.as_type(), crate_ident)))
        .collect();
    let ret_info = m.return_type().map(|t| classify(t, crate_ident));

    if let Some(reason) = first_unsupported(&arg_info, &ret_info) {
        let params = arg_info
            .iter()
            .map(|(n, _)| format!("_{n}: JsValue"))
            .collect::<Vec<_>>()
            .join(", ");
        let comma = if params.is_empty() { "" } else { ", " };
        writeln!(out, "#[wasm_bindgen]").unwrap();
        writeln!(
            out,
            "pub fn {fn_name}(_handle: u32{comma}{params}) -> Result<JsValue, JsError> {{\n    \
             Err(JsError::new(\"method not yet lowered: {reason}\"))\n\
             }}"
        )
        .unwrap();
        return;
    }

    let is_async = m.is_async();
    let throws = m.throws_type().is_some();
    let async_kw = if is_async { "async " } else { "" };
    let call_await = if is_async { ".await" } else { "" };

    let params = param_list(&arg_info);
    let comma = if params.is_empty() { "" } else { ", " };
    let rust_ret = return_type(&ret_info, throws);

    writeln!(out, "#[wasm_bindgen]").unwrap();
    writeln!(
        out,
        "pub {async_kw}fn {fn_name}(handle: u32{comma}{params}) -> {rust_ret} {{"
    )
    .unwrap();
    writeln!(out, "    let __self = __uniffi_{snake}_get(handle)?;").unwrap();
    emit_arg_decoders(out, &arg_info);
    let pass = arg_pass(&arg_info);
    let call = format!("__self.{}({pass}){call_await}", m.name());
    let bound = if throws {
        format!("{call}.map_err(|e| JsError::new(&format!(\"{{e:?}}\")))?")
    } else {
        call
    };
    emit_return(out, &ret_info, &bound);
    writeln!(out, "}}").unwrap();
}

