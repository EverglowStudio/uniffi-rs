fn stream_child_bindings(
    binding: &RustValueBinding,
) -> Option<(RustValueBinding, RustValueBinding)> {
    match (&binding.rust_type, &binding.conversion) {
        (
            RustType::InputStream { item, error, .. },
            ConversionRecipe::InputStream {
                item: item_conversion,
                error: error_conversion,
            },
        )
        | (
            RustType::Stream { item, error, .. },
            ConversionRecipe::OutputStream {
                item: item_conversion,
                error: error_conversion,
            },
        ) => Some((
            RustValueBinding {
                rust_type: (**item).clone(),
                carrier: RustCarrier::LocalAdapter,
                conversion: (**item_conversion).clone(),
            },
            RustValueBinding {
                rust_type: (**error).clone(),
                carrier: RustCarrier::LocalAdapter,
                conversion: (**error_conversion).clone(),
            },
        )),
        _ => None,
    }
}

/// Collect every stream binding reachable from the canonical Rust plan.  The
/// operation resource groups remain the source of direct stream slots; these
/// additional bindings only provide typed adapters for streams nested in
/// records/variants/containers.
fn collect_stream_bindings(package: &NormalizedPackage) -> Result<Vec<RustValueBinding>> {
    fn visit(
        package: &NormalizedPackage,
        binding: &RustValueBinding,
        visiting: &mut BTreeSet<TypeId>,
        out: &mut BTreeMap<String, RustValueBinding>,
    ) -> Result<()> {
        match &binding.conversion {
            ConversionRecipe::InputStream { .. } | ConversionRecipe::OutputStream { .. } => {
                out.entry(stream_adapter_suffix(binding))
                    .or_insert_with(|| binding.clone());
                if let Some((item, error)) = stream_child_bindings(binding) {
                    visit(package, &item, visiting, out)?;
                    visit(package, &error, visiting, out)?;
                }
            }
            ConversionRecipe::Optional(inner)
            | ConversionRecipe::Sequence(inner)
            | ConversionRecipe::Set(inner) => {
                let nested = nested_binding(binding, inner, RustType::Unit);
                visit(package, &nested, visiting, out)?;
            }
            ConversionRecipe::Custom(id, _) => {
                let Some(named) = package.rust.named_type(*id) else {
                    return Err(anyhow!("unknown custom type {}", id.index()));
                };
                if let RustNamedTypeKind::Custom { inner, .. } = &named.kind {
                    visit(package, inner, visiting, out)?;
                }
            }
            ConversionRecipe::Map(key, value) => {
                let (key_binding, value_binding) = map_bindings(binding, key, value);
                visit(package, &key_binding, visiting, out)?;
                visit(package, &value_binding, visiting, out)?;
            }
            ConversionRecipe::Record(id) => {
                if !visiting.insert(*id) {
                    return Ok(());
                }
                let result = package
                    .rust
                    .named_type(*id)
                    .ok_or_else(|| anyhow!("unknown record type {}", id.index()))
                    .and_then(|named| match &named.kind {
                        RustNamedTypeKind::Record { fields } => {
                            for field in fields {
                                visit(package, &field.binding, visiting, out)?;
                            }
                            Ok(())
                        }
                        _ => Ok(()),
                    });
                visiting.remove(id);
                result?;
            }
            ConversionRecipe::Enum(id) | ConversionRecipe::Error(id) => {
                if !visiting.insert(*id) {
                    return Ok(());
                }
                let result = package
                    .rust
                    .named_type(*id)
                    .ok_or_else(|| anyhow!("unknown enum/error type {}", id.index()))
                    .and_then(|named| match &named.kind {
                        RustNamedTypeKind::Enum { variants }
                        | RustNamedTypeKind::Error { variants } => {
                            for variant in variants {
                                match &variant.payload {
                                    RustVariantPayload::Named(fields) => {
                                        for field in fields {
                                            visit(package, &field.binding, visiting, out)?;
                                        }
                                    }
                                    RustVariantPayload::Tuple(fields) => {
                                        for field in fields {
                                            visit(package, &field.binding, visiting, out)?;
                                        }
                                    }
                                    RustVariantPayload::Unit => {}
                                }
                            }
                            Ok(())
                        }
                        _ => Ok(()),
                    });
                visiting.remove(id);
                result?;
            }
            ConversionRecipe::Identity
            | ConversionRecipe::Timestamp
            | ConversionRecipe::Duration
            | ConversionRecipe::BigInt
            | ConversionRecipe::Bytes
            | ConversionRecipe::Object(_)
            | ConversionRecipe::Callback(_)
            | ConversionRecipe::StreamStep { .. } => {}
        }
        Ok(())
    }

    let mut out = BTreeMap::new();
    let mut visiting = BTreeSet::new();
    for named in package.rust.named_types() {
        match &named.kind {
            RustNamedTypeKind::Record { fields } => {
                for field in fields {
                    visit(package, &field.binding, &mut visiting, &mut out)?;
                }
            }
            RustNamedTypeKind::Enum { variants } | RustNamedTypeKind::Error { variants } => {
                for variant in variants {
                    match &variant.payload {
                        RustVariantPayload::Named(fields) => {
                            for field in fields {
                                visit(package, &field.binding, &mut visiting, &mut out)?;
                            }
                        }
                        RustVariantPayload::Tuple(fields) => {
                            for field in fields {
                                visit(package, &field.binding, &mut visiting, &mut out)?;
                            }
                        }
                        RustVariantPayload::Unit => {}
                    }
                }
            }
            RustNamedTypeKind::Custom { inner, .. } => {
                visit(package, inner, &mut visiting, &mut out)?;
            }
            RustNamedTypeKind::Object { .. } | RustNamedTypeKind::Callback => {}
        }
    }
    for operations in package.rust.engines.values() {
        for operation in &operations.operations {
            if let Some(receiver) = &operation.receiver {
                visit(
                    package,
                    &RustValueBinding {
                        rust_type: receiver.rust_type.clone(),
                        carrier: receiver.carrier,
                        conversion: receiver.conversion.clone(),
                    },
                    &mut visiting,
                    &mut out,
                )?;
            }
            for (index, argument) in operation.arguments.iter().enumerate() {
                // Direct stream slots are owned by the operation's stream
                // resource group and get a dedicated adapter below.  Do not
                // also collect them as nested adapters: that would emit an
                // unreferenced private ops struct and fail consumers that
                // compile generated hosts with `-D warnings`.
                if operation.stream_resources.iter().any(|group| {
                    matches!(
                        group.path.segments(),
                        [uniffi_js_engine_schema::ValuePathSegment::Argument(argument_index)]
                            if *argument_index == index as u32
                    )
                }) {
                    continue;
                }
                visit(
                    package,
                    &RustValueBinding {
                        rust_type: argument.rust_type.clone(),
                        carrier: argument.carrier,
                        conversion: argument.conversion.clone(),
                    },
                    &mut visiting,
                    &mut out,
                )?;
            }
            if let Some(return_value) = &operation.return_value {
                let direct_stream_return = operation.stream_resources.iter().any(|group| {
                    matches!(
                        group.path.segments(),
                        [uniffi_js_engine_schema::ValuePathSegment::Return]
                    )
                });
                if !direct_stream_return {
                    visit(
                        package,
                        &RustValueBinding {
                            rust_type: return_value.rust_type.clone(),
                            carrier: return_value.carrier,
                            conversion: return_value.conversion.clone(),
                        },
                        &mut visiting,
                        &mut out,
                    )?;
                }
            }
        }
    }
    Ok(out.into_values().collect())
}

fn render_nested_stream_adapter(
    package: &NormalizedPackage,
    binding: &RustValueBinding,
) -> Result<TokenStream> {
    let Some((item_binding, error_binding)) = stream_child_bindings(binding) else {
        return Ok(TokenStream::new());
    };
    let item = core_type(package, &item_binding)?;
    let error = core_type(package, &error_binding)?;
    let suffix = stream_adapter_suffix(binding);
    match &binding.conversion {
        ConversionRecipe::InputStream { .. } => {
            let ops = rust_ident(&format!(
                "UniffiWasmNestedInputOps{}",
                stream_adapter_type_suffix(binding)
            ));
            let make = nested_input_make_ident(binding);
            let lower = nested_input_lower_ident(binding);
            let lower_item = lower_js_expr(package, &item_binding, quote!(value))?;
            let lower_error = lower_js_expr(package, &error_binding, quote!(value))?;
            Ok(quote! {
                struct #ops { host: JsValue }
                impl ::uniffi::ForeignInputStreamOps<#item, #error> for #ops {
                    fn next(&self, handle: ::uniffi::Handle) -> ::uniffi::ForeignInputStreamNextFuture<#item, #error> {
                        let host = self.host.clone();
                        Box::pin(async move {
                            let pull = js_sys::Reflect::get(&host, &JsValue::from_str("pullInputStream"))
                                .expect("wasm input stream host is missing pullInputStream")
                                .dyn_into::<js_sys::Function>()
                                .expect("wasm input stream pullInputStream is not callable");
                            let raw = pull.call1(&JsValue::NULL, &JsValue::from_f64(handle.as_raw() as f64))
                                .expect("wasm input stream pullInputStream threw");
                            let promise = if raw.is_instance_of::<js_sys::Promise>() {
                                raw.dyn_into::<js_sys::Promise>().expect("invalid input stream promise")
                            } else { js_sys::Promise::resolve(&raw) };
                            let envelope = wasm_bindgen_futures::JsFuture::from(promise)
                                .await
                                .expect("wasm input stream pullInputStream rejected");
                            let object: js_sys::Object = envelope.dyn_into()
                                .expect("wasm input stream host returned a non-object envelope");
                            let kind = js_sys::Reflect::get(&object, &JsValue::from_str("kind"))
                                .expect("wasm input stream envelope missing kind")
                                .as_string()
                                .expect("wasm input stream envelope kind is not a string");
                            match kind.as_str() {
                                "done" => Ok(None),
                                "item" => {
                                    let value = js_sys::Reflect::get(&object, &JsValue::from_str("value"))
                                        .expect("wasm input stream envelope missing value");
                                    __uniffi_set_call_host(Some(host.clone()));
                                    let lowered = (#lower_item).expect("wasm input stream item lowering failed");
                                    __uniffi_set_call_host(None);
                                    Ok(Some(lowered))
                                }
                                "error" => {
                                    let value = js_sys::Reflect::get(&object, &JsValue::from_str("error"))
                                        .expect("wasm input stream envelope missing error");
                                    __uniffi_set_call_host(Some(host.clone()));
                                    let lowered = (#lower_error).expect("wasm input stream error lowering failed");
                                    __uniffi_set_call_host(None);
                                    Err(lowered)
                                }
                                other => panic!("wasm input stream envelope has an unknown kind: {other}"),
                            }
                        })
                    }
                    fn cancel(&self, handle: ::uniffi::Handle) {
                        let cancel = js_sys::Reflect::get(&self.host, &JsValue::from_str("cancelInputStream"))
                            .expect("wasm input stream host is missing cancelInputStream")
                            .dyn_into::<js_sys::Function>()
                            .expect("wasm input stream cancelInputStream is not callable");
                        cancel.call1(&JsValue::NULL, &JsValue::from_f64(handle.as_raw() as f64))
                            .expect("wasm input stream cancelInputStream threw");
                    }
                }
                fn #make(host: JsValue, handle: u32) -> ::uniffi::UniFfiInputStream<#item, #error> {
                    ::uniffi::UniFfiInputStream::from_handle_and_ops(
                        ::uniffi::Handle::from_raw_unchecked(handle as u64),
                        ::std::sync::Arc::new(#ops { host }),
                    )
                }
                fn #lower(handle: u32) -> Result<::uniffi::UniFfiInputStream<#item, #error>, JsValue> {
                    Ok(#make(__uniffi_call_host()?, handle))
                }
            })
        }
        ConversionRecipe::OutputStream { .. } => {
            let registry = rust_ident(&format!(
                "__UNIFFI_WASM_NESTED_OUTPUT_REGISTRY_{}",
                suffix.to_ascii_uppercase()
            ));
            let lift = nested_output_lift_ident(binding);
            let close = nested_output_close_ident(binding);
            Ok(quote! {
                static #registry: ::uniffi::RustStreamRegistry<#item, #error> =
                    ::uniffi::deps::once_cell::sync::Lazy::new(|| {
                        ::std::sync::Mutex::new(::std::collections::HashMap::new())
                    });
                fn #lift(value: ::uniffi::UniFfiStream<#item, #error>) -> Result<JsValue, JsValue> {
                    let handle = ::uniffi::rust_stream_new(&#registry, value);
                    Ok(JsValue::from_f64(handle.as_raw() as f64))
                }
                fn #close(handle: u32) {
                    ::uniffi::rust_stream_cancel::<#item, #error>(
                        &#registry,
                        ::uniffi::Handle::from_raw_unchecked(handle as u64),
                    );
                }
            })
        }
        _ => Ok(TokenStream::new()),
    }
}

fn render_stream_helpers(package: &NormalizedPackage) -> Result<String> {
    let mut tokens = TokenStream::new();
    let mut output_closers = Vec::new();
    let nested_bindings = collect_stream_bindings(package)?;
    for binding in &nested_bindings {
        tokens.extend(render_nested_stream_adapter(package, binding)?);
        if matches!(&binding.conversion, ConversionRecipe::OutputStream { .. }) {
            let close = nested_output_close_ident(binding);
            output_closers.push(quote!(#close(handle);));
        }
    }
    for operation in &package.rust.engines[&EngineKind::WasmBindgen].operations {
        for group in &operation.stream_resources {
            let item = core_type(package, &group.item)?;
            let error = core_type(package, &group.error)?;
            let suffix = format!("{}_{}", operation.operation_id.index(), group.id.index());
            let registry = rust_ident(&format!("__UNIFFI_WASM_OUTPUT_REGISTRY_{suffix}"));
            let close = rust_ident(&format!("__uniffi_close_output_stream_{suffix}"));
            if group.direction == uniffi_js_engine_schema::StreamDirection::Output {
                output_closers.push(quote!(#close(handle);));
                tokens.extend(quote! {
                    static #registry: ::uniffi::RustStreamRegistry<#item, #error> =
                        ::uniffi::deps::once_cell::sync::Lazy::new(|| {
                            ::std::sync::Mutex::new(::std::collections::HashMap::new())
                        });
                    fn #close(handle: u32) {
                        ::uniffi::rust_stream_cancel::<#item, #error>(
                            &#registry,
                            ::uniffi::Handle::from_raw_unchecked(handle as u64),
                        );
                    }
                });
            }
            if group.direction == uniffi_js_engine_schema::StreamDirection::Input {
                let ops = rust_ident(&format!(
                    "UniffiWasmInputOps{}{}",
                    operation.operation_id.index(),
                    group.id.index()
                ));
                let make = rust_ident(&format!("__uniffi_make_input_stream_{suffix}"));
                let lower_item = lower_js_expr(package, &group.item, quote!(value))?;
                let lower_error = lower_js_expr(package, &group.error, quote!(value))?;
                tokens.extend(quote! {
                    struct #ops { host: JsValue }
                    impl ::uniffi::ForeignInputStreamOps<#item, #error> for #ops {
                        fn next(&self, handle: ::uniffi::Handle) -> ::uniffi::ForeignInputStreamNextFuture<#item, #error> {
                            let host = self.host.clone();
                            Box::pin(async move {
                                let pull = js_sys::Reflect::get(&host, &JsValue::from_str("pullInputStream"))
                                    .expect("wasm input stream host is missing pullInputStream")
                                    .dyn_into::<js_sys::Function>()
                                    .expect("wasm input stream pullInputStream is not callable");
                                let raw = pull.call1(&JsValue::NULL, &JsValue::from_f64(handle.as_raw() as f64))
                                    .expect("wasm input stream pullInputStream threw");
                                let promise = if raw.is_instance_of::<js_sys::Promise>() {
                                    raw.dyn_into::<js_sys::Promise>().expect("invalid input stream promise")
                                } else {
                                    js_sys::Promise::resolve(&raw)
                                };
                                let envelope = wasm_bindgen_futures::JsFuture::from(promise)
                                    .await
                                    .expect("wasm input stream pullInputStream rejected");
                                let object: js_sys::Object = envelope.dyn_into()
                                    .expect("wasm input stream host returned a non-object envelope");
                                let kind = js_sys::Reflect::get(&object, &JsValue::from_str("kind"))
                                    .expect("wasm input stream envelope missing kind")
                                    .as_string()
                                    .expect("wasm input stream envelope kind is not a string");
                                // A protocol error is not a value of the
                                // declared stream error type.  Only an
                                // explicit `kind: "error"` envelope can be
                                // lowered into `#error`; malformed envelopes
                                // therefore fail the host call instead of
                                // being silently treated as completion.
                                match kind.as_str() {
                                    "done" => Ok(None),
                                    "item" => {
                                        let value = js_sys::Reflect::get(&object, &JsValue::from_str("value"))
                                            .expect("wasm input stream envelope missing value");
                                        __uniffi_set_call_host(Some(host.clone()));
                                        let lowered = (#lower_item).expect("wasm input stream item lowering failed");
                                        __uniffi_set_call_host(None);
                                        Ok(Some(lowered))
                                    }
                                    "error" => {
                                        let value = js_sys::Reflect::get(&object, &JsValue::from_str("error"))
                                            .expect("wasm input stream envelope missing error");
                                        __uniffi_set_call_host(Some(host.clone()));
                                        let lowered = (#lower_error).expect("wasm input stream error lowering failed");
                                        __uniffi_set_call_host(None);
                                        Err(lowered)
                                    }
                                    other => panic!(
                                        "wasm input stream envelope has an unknown kind: {other}"
                                    ),
                                }
                            })
                        }
                        fn cancel(&self, handle: ::uniffi::Handle) {
                            let value = js_sys::Reflect::get(
                                &self.host,
                                &JsValue::from_str("cancelInputStream"),
                            )
                            .expect("wasm input stream host is missing cancelInputStream");
                            let cancel = value
                                .dyn_into::<js_sys::Function>()
                                .expect("wasm input stream cancelInputStream is not callable");
                            cancel
                                .call1(
                                    &JsValue::NULL,
                                    &JsValue::from_f64(handle.as_raw() as f64),
                                )
                                .expect("wasm input stream cancelInputStream threw");
                        }
                    }
                    fn #make(host: JsValue, handle: u32) -> ::uniffi::UniFfiInputStream<#item, #error> {
                        ::uniffi::UniFfiInputStream::from_handle_and_ops(
                            ::uniffi::Handle::from_raw_unchecked(handle as u64),
                            ::std::sync::Arc::new(#ops { host }),
                        )
                    }
                });
            }
        }
    }
    tokens.extend(quote! {
        #[doc(hidden)]
        fn __uniffi_wasm_close_output_stream_impl(handle: u32) -> Result<(), JsValue> {
            #(#output_closers)*
            // Output streams and objects live in independent registries and
            // may legitimately receive the same numeric handle. Releasing an
            // object here would therefore dispose an unrelated live object.
            Ok(())
        }
    });
    Ok(tokens.to_string())
}

fn is_host_dispatched_operation(operation: &RustOperationPlan) -> bool {
    match &operation.call_target {
        RustCallTarget::CallbackMethod { .. } => true,
        RustCallTarget::StreamHook { hook, .. } => matches!(
            hook,
            uniffi_js_engine_schema::RustResourceHook::PullInputStream
                | uniffi_js_engine_schema::RustResourceHook::CancelInputStream
        ),
        _ => false,
    }
}

/// Lower one operation argument/receiver while preserving the operation's
/// declared fallibility.  The wasm engine ABI uses the raw carrier type for a
/// non-throwing operation, so a conversion failure cannot be propagated with
/// `?` from that wrapper.  Such failures indicate a malformed public value
/// (the facade validates the same contract before invocation) and are made
/// explicit as a panic; fallible operations retain their declared `Result`
/// path and propagate the `JsValue` error.
fn lower_operation_value(expression: TokenStream, fallible: bool, context: &str) -> TokenStream {
    // Nested/container lowerers use `?` while decoding their JsValue fields.
    // Evaluate every conversion in a Result-returning closure so the outer
    // wasm ABI wrapper (which returns a raw carrier for non-throws operations)
    // never receives a stray `?` token.
    let expression = quote!((|| -> Result<_, JsValue> { #expression })());
    if fallible {
        quote!(#expression?)
    } else {
        let message = format!("wasm {context} lowering failed");
        quote! {
            match #expression {
                Ok(value) => value,
                Err(error) => panic!("{}: {:?}", #message, error),
            }
        }
    }
}

fn render_operations(package: &NormalizedPackage) -> Result<String> {
    let mut tokens = TokenStream::new();
    for operation in &package.rust.engines[&EngineKind::WasmBindgen].operations {
        // Callback methods and input-stream pull/cancel are dispatched by the
        // wasm-bindgen host session.  The engine expansion deliberately omits
        // their raw ABI descriptors, so the typed renderer must omit their
        // wrappers as well.  Keeping a second throw/no-op export here would
        // create an unreferenced public ABI surface and could diverge from the
        // host dispatch contract.
        if is_host_dispatched_operation(operation) {
            continue;
        }
        if operation.kind == uniffi_js_abi::OperationKind::OutputStreamStart {
            tokens.extend(render_output_stream_start(package, operation)?);
            continue;
        }
        if matches!(operation.call_target, RustCallTarget::StreamHook { .. }) {
            tokens.extend(render_stream_hook_operation(package, operation)?);
            continue;
        }
        let wrapper = rust_ident(&format!(
            "__uniffi_typed_wasm_operation_{}",
            operation.operation_id.index()
        ));
        let async_fn = matches!(operation.async_kind, uniffi_js_abi::AsyncKind::Async);
        let async_token = async_fn.then(|| quote!(async));
        let needs_host = operation.callback_use_sites(package).unwrap_or(false);
        let mut params = Vec::new();
        let mut call_arguments = Vec::new();
        let mut lowered_arguments = Vec::new();
        if needs_host {
            params.push(quote!(host: JsValue));
            lowered_arguments.push(quote!(__uniffi_set_call_host(Some(host.clone()));));
        }
        if let Some(receiver) = &operation.receiver {
            let binding = RustValueBinding {
                rust_type: receiver.rust_type.clone(),
                carrier: receiver.carrier,
                conversion: receiver.conversion.clone(),
            };
            let ty = wasm_param_type(&binding);
            params.push(quote!(receiver: #ty));
            let receiver_value = rust_ident("__uniffi_receiver");
            let lowered = lower_expr(package, &binding, quote!(receiver))?;
            let lowered = lower_operation_value(lowered, operation.throws.is_some(), "receiver");
            lowered_arguments.push(quote!(let #receiver_value = #lowered;));
            call_arguments.push(quote!(#receiver_value));
        }
        for (index, argument) in operation.arguments.iter().enumerate() {
            let binding = RustValueBinding {
                rust_type: argument.rust_type.clone(),
                carrier: argument.carrier,
                conversion: argument.conversion.clone(),
            };
            let arg = rust_ident(&format!("arg{index}"));
            let ty = wasm_param_type(&binding);
            params.push(quote!(#arg: #ty));
            let core_arg = rust_ident(&format!("__uniffi_arg_{index}"));
            let input_group = operation.stream_resources.iter().find(|group| {
                group.direction == uniffi_js_engine_schema::StreamDirection::Input
                    && matches!(
                        group.path.segments(),
                        [uniffi_js_engine_schema::ValuePathSegment::Argument(argument_index)]
                            if *argument_index == index as u32
                    )
            });
            if let Some(group) = input_group {
                let make =
                    input_stream_make_ident(operation.operation_id.index(), group.id.index());
                lowered_arguments.push(quote!(
                    let #core_arg = #make(host.clone(), #arg);
                ));
            } else {
                let lowered = lower_expr(package, &binding, quote!(#arg))?;
                let lowered =
                    lower_operation_value(lowered, operation.throws.is_some(), "argument");
                lowered_arguments.push(quote!(let #core_arg = #lowered;));
            }
            call_arguments.push(rust_call_argument(quote!(#core_arg), argument.ownership));
        }
        let return_binding = operation
            .return_value
            .as_ref()
            .map(|binding| RustValueBinding {
                rust_type: binding.rust_type.clone(),
                carrier: binding.carrier,
                conversion: binding.conversion.clone(),
            });
        let return_ty = return_binding
            .as_ref()
            .map(wasm_param_type)
            .unwrap_or_else(|| quote!(()));
        let declared_error_lift = match operation.throws {
            Some(error_id) => {
                let binding = declared_error_binding(package, error_id)?;
                Some(lift_js_expr(package, &binding, quote!(error))?)
            }
            None => None,
        };
        let output = if operation.throws.is_some() {
            quote!(Result<#return_ty, JsValue>)
        } else {
            return_ty.clone()
        };
        let call = render_call(package, operation, &call_arguments)?;
        // Callback proxies retain the host object, but callback-return
        // lowerers also need the current host while the native call is in
        // flight (for example when a callback returns another callback
        // proxy). Keep the call-host cell populated through completion and
        // clear it only afterwards.
        let call = if async_fn {
            if needs_host {
                quote! {
                    {
                        let __uniffi_call_result = #call.await;
                        __uniffi_set_call_host(None);
                        __uniffi_call_result
                    }
                }
            } else {
                quote!(#call.await)
            }
        } else if needs_host {
            quote! {
                {
                    let __uniffi_call_result = #call;
                    __uniffi_set_call_host(None);
                    __uniffi_call_result
                }
            }
        } else {
            call
        };
        let call = if operation.throws.is_some() {
            let error_lift = declared_error_lift
                .as_ref()
                .expect("declared operation error has a lift expression");
            if return_binding.is_some() {
                quote! {
                    let result = #call;
                    let result = match result {
                        Ok(value) => value,
                        Err(error) => return Err((#error_lift)?),
                    };
                }
            } else {
                quote! {
                    match #call {
                        Ok(()) => {},
                        Err(error) => return Err((#error_lift)?),
                    }
                }
            }
        } else if return_binding.is_some() {
            quote!(let result = #call;)
        } else {
            quote!(#call;)
        };
        let lifted = if let Some(binding) = &return_binding {
            let expression = lift_expr(package, binding, quote!(result))?;
            let expression = quote!((|| -> Result<#return_ty, JsValue> { #expression })());
            if operation.throws.is_some() {
                quote!(#expression)
            } else {
                // A non-throwing operation still has fallible JS boundary
                // conversions (for example, a SystemTime outside Date's
                // representable range).  Convert those failures into a JS
                // exception instead of panicking through `expect`, so the
                // generated facade preserves the normal host error channel.
                quote! {
                    match #expression {
                        Ok(value) => value,
                        Err(error) => wasm_bindgen::throw_val(error),
                    }
                }
            }
        } else if operation.throws.is_some() {
            quote!(Ok(()))
        } else {
            quote!(())
        };
        tokens.extend(quote! {
            #[doc(hidden)]
            #async_token fn #wrapper(#(#params),*) -> #output {
                #(#lowered_arguments)*
                #call
                #lifted
            }
        });
    }
    Ok(tokens.to_string())
}

fn render_output_stream_start(
    package: &NormalizedPackage,
    operation: &RustOperationPlan,
) -> Result<TokenStream> {
    let group = operation
        .stream_resources
        .iter()
        .find(|group| group.direction == uniffi_js_engine_schema::StreamDirection::Output)
        .ok_or_else(|| anyhow!("output stream start has no output resource group"))?;
    let wrapper = rust_ident(&format!(
        "__uniffi_typed_wasm_operation_{}",
        operation.operation_id.index()
    ));
    let registry = output_stream_registry_ident(operation.operation_id.index(), group.id.index());
    let needs_host = operation.callback_use_sites(package).unwrap_or(false);
    let mut params = Vec::new();
    let mut lowered = Vec::new();
    let mut arguments = Vec::new();
    if needs_host {
        params.push(quote!(host: JsValue));
        lowered.push(quote!(__uniffi_set_call_host(Some(host.clone()));));
    }
    if let Some(receiver) = &operation.receiver {
        let binding = RustValueBinding {
            rust_type: receiver.rust_type.clone(),
            carrier: receiver.carrier,
            conversion: receiver.conversion.clone(),
        };
        let ty = wasm_param_type(&binding);
        params.push(quote!(receiver: #ty));
        let value = lower_expr(package, &binding, quote!(receiver))?;
        let value = lower_operation_value(value, operation.throws.is_some(), "receiver");
        lowered.push(quote!(let receiver_value = #value;));
        arguments.push(quote!(receiver_value));
    }
    for (index, argument) in operation.arguments.iter().enumerate() {
        let binding = RustValueBinding {
            rust_type: argument.rust_type.clone(),
            carrier: argument.carrier,
            conversion: argument.conversion.clone(),
        };
        let arg = rust_ident(&format!("arg{index}"));
        let ty = wasm_param_type(&binding);
        params.push(quote!(#arg: #ty));
        let value = lower_expr(package, &binding, quote!(#arg))?;
        let core = rust_ident(&format!("__uniffi_arg_{index}"));
        let input_group = operation.stream_resources.iter().find(|group| {
            group.direction == uniffi_js_engine_schema::StreamDirection::Input
                && matches!(
                    group.path.segments(),
                    [uniffi_js_engine_schema::ValuePathSegment::Argument(argument_index)]
                        if *argument_index == index as u32
                )
        });
        if let Some(group) = input_group {
            let make = input_stream_make_ident(operation.operation_id.index(), group.id.index());
            lowered.push(quote!(let #core = #make(host.clone(), #arg);));
        } else {
            let value = lower_operation_value(value, operation.throws.is_some(), "argument");
            lowered.push(quote!(let #core = #value;));
        }
        arguments.push(rust_call_argument(quote!(#core), argument.ownership));
    }
    if needs_host {
        lowered.push(quote!(__uniffi_set_call_host(None);));
    }
    let call = render_call(package, operation, &arguments)?;
    let call = if operation.async_kind == uniffi_js_abi::AsyncKind::Async {
        quote!(#call.await)
    } else {
        call
    };
    let item = core_type(package, &group.item)?;
    let error = core_type(package, &group.error)?;
    let declared_error_lift = match operation.throws {
        Some(error_id) => {
            let binding = declared_error_binding(package, error_id)?;
            Some(lift_js_expr(package, &binding, quote!(error))?)
        }
        None => None,
    };
    let output = if operation.throws.is_some() {
        quote!(Result<u32, JsValue>)
    } else {
        quote!(u32)
    };
    let invoke = if operation.throws.is_some() {
        let error_lift = declared_error_lift
            .as_ref()
            .expect("declared stream start error has a lift expression");
        quote! {
            let stream: ::uniffi::UniFfiStream<#item, #error> = match #call {
                Ok(stream) => stream,
                Err(error) => return Err((#error_lift)?),
            };
            let handle = ::uniffi::rust_stream_new(&#registry, stream);
            Ok(handle.as_raw() as u32)
        }
    } else {
        quote! {
            let stream: ::uniffi::UniFfiStream<#item, #error> = #call;
            let handle = ::uniffi::rust_stream_new(&#registry, stream);
            handle.as_raw() as u32
        }
    };
    let body = invoke;
    let call_body = body;
    Ok(quote! {
        #[doc(hidden)]
        fn #wrapper(#(#params),*) -> #output {
            #(#lowered)*
            #call_body
        }
    })
}

fn input_stream_make_ident(operation_id: u32, group_id: u32) -> Ident {
    rust_ident(&format!(
        "__uniffi_make_input_stream_{operation_id}_{group_id}"
    ))
}

fn output_stream_registry_ident(operation_id: u32, group_id: u32) -> Ident {
    rust_ident(&format!(
        "__UNIFFI_WASM_OUTPUT_REGISTRY_{operation_id}_{group_id}"
    ))
}

fn stream_group_for_hook<'a>(
    package: &'a NormalizedPackage,
    operation: &RustOperationPlan,
) -> Result<&'a uniffi_js_engine_schema::RustStreamResourceGroup> {
    let RustCallTarget::StreamHook {
        parent,
        use_site_id,
        ..
    } = operation.call_target
    else {
        return Err(anyhow!("operation is not a stream hook"));
    };
    let parent_operation = package.rust.engines[&EngineKind::WasmBindgen]
        .operations
        .iter()
        .find(|candidate| candidate.operation_id == parent)
        .ok_or_else(|| {
            anyhow!(
                "stream hook references unknown parent operation {}",
                parent.index()
            )
        })?;
    parent_operation
        .stream_resources
        .iter()
        .find(|group| group.id == use_site_id)
        .ok_or_else(|| {
            anyhow!(
                "stream hook references unknown stream group {}",
                use_site_id.index()
            )
        })
}

fn render_stream_hook_operation(
    package: &NormalizedPackage,
    operation: &RustOperationPlan,
) -> Result<TokenStream> {
    let group = stream_group_for_hook(package, operation)?;
    let wrapper = rust_ident(&format!(
        "__uniffi_typed_wasm_operation_{}",
        operation.operation_id.index()
    ));
    let receiver = quote!(receiver: u32);
    let registry = output_stream_registry_ident(
        match operation.call_target {
            RustCallTarget::StreamHook { parent, .. } => parent.index(),
            _ => unreachable!(),
        },
        group.id.index(),
    );
    let handle = quote!(::uniffi::Handle::from_raw_unchecked(receiver as u64));
    let hook = match operation.call_target {
        RustCallTarget::StreamHook { hook, .. } => hook,
        _ => unreachable!(),
    };
    match hook {
        uniffi_js_engine_schema::RustResourceHook::PullOutputStream => {
            let item_binding = &group.item;
            let error_binding = &group.error;
            let item = core_type(package, item_binding)?;
            let error = core_type(package, error_binding)?;
            let item_lift = lift_js_expr(package, item_binding, quote!(value))?;
            let error_lift = lift_js_expr(package, error_binding, quote!(error))?;
            Ok(quote! {
                #[doc(hidden)]
                async fn #wrapper(#receiver) -> JsValue {
                    match ::uniffi::rust_stream_next_async::<#item, #error>(&#registry, #handle).await
                        .unwrap_or_else(|error| panic!("wasm output stream next failed: {error:?}")) {
                        ::uniffi::UniFfiStreamStep::Item(value) => {
                            let object = js_sys::Object::new();
                            js_sys::Reflect::set(&object, &JsValue::from_str("kind"), &JsValue::from_str("item"))
                                .expect("wasm output stream item envelope kind write failed");
                            let lifted = (#item_lift)
                                .expect("wasm output stream item lifting failed");
                            js_sys::Reflect::set(&object, &JsValue::from_str("value"), &lifted)
                                .expect("wasm output stream item envelope value write failed");
                            object.into()
                        }
                        ::uniffi::UniFfiStreamStep::Done => {
                            let object = js_sys::Object::new();
                            js_sys::Reflect::set(&object, &JsValue::from_str("kind"), &JsValue::from_str("done"))
                                .expect("wasm output stream done envelope write failed");
                            object.into()
                        }
                        ::uniffi::UniFfiStreamStep::Error(error) => {
                            let object = js_sys::Object::new();
                            js_sys::Reflect::set(&object, &JsValue::from_str("kind"), &JsValue::from_str("error"))
                                .expect("wasm output stream error envelope kind write failed");
                            let lifted = (#error_lift)
                                .expect("wasm output stream error lifting failed");
                            js_sys::Reflect::set(&object, &JsValue::from_str("error"), &lifted)
                                .expect("wasm output stream error envelope value write failed");
                            object.into()
                        }
                    }
                }
            })
        }
        uniffi_js_engine_schema::RustResourceHook::CancelOutputStream => {
            let item = core_type(package, &group.item)?;
            let error = core_type(package, &group.error)?;
            Ok(quote! {
                #[doc(hidden)]
                async fn #wrapper(#receiver) {
                    ::uniffi::rust_stream_cancel::<#item, #error>(&#registry, #handle);
                }
            })
        }
        _ => Err(anyhow!(
            "host-dispatched stream hook must not be rendered as a native wasm operation"
        )),
    }
}

fn render_call(
    package: &NormalizedPackage,
    operation: &RustOperationPlan,
    arguments: &[TokenStream],
) -> Result<TokenStream> {
    let args = arguments
        .iter()
        .skip(usize::from(operation.receiver.is_some()));
    let call = match &operation.call_target {
        RustCallTarget::FreeFunction { module, item } => {
            let module = rust_path(module)?;
            let item = rust_ident(item);
            quote!(#module::#item(#(#args),*))
        }
        RustCallTarget::Constructor { object, item, .. } => {
            let object = rust_path(object)?;
            let item = rust_ident(item);
            quote!(#object::#item(#(#args),*))
        }
        RustCallTarget::Method { item, .. } => {
            let receiver = arguments
                .first()
                .cloned()
                .unwrap_or_else(|| quote!(receiver));
            let item = rust_ident(item);
            quote!(#receiver.#item(#(#args),*))
        }
        // Host-dispatched operations are filtered before reaching this
        // renderer.  Return a generation-time error if a future caller
        // accidentally routes one through the native call path instead of
        // emitting an unreferenced throw/no-op wrapper.
        RustCallTarget::CallbackMethod { .. } | RustCallTarget::StreamHook { .. } => {
            return Err(anyhow!(
                "host-dispatched operation must not be rendered as a native wasm call"
            ));
        }
    };
    let _ = package;
    Ok(call)
}

trait OperationHostRequirement {
    fn callback_use_sites(&self, package: &NormalizedPackage) -> Result<bool>;
}

impl OperationHostRequirement for RustOperationPlan {
    fn callback_use_sites(&self, package: &NormalizedPackage) -> Result<bool> {
        let callbacks = package
            .bridge
            .callbacks()
            .iter()
            .any(|callback| callback.operation_id == self.operation_id);
        let input_stream = self
            .stream_resources
            .iter()
            .any(|group| group.direction == uniffi_js_engine_schema::StreamDirection::Input);
        Ok(callbacks || input_stream)
    }
}

