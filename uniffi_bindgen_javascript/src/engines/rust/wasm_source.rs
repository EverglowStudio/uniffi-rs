/// Build a stable, source-local suffix for one typed stream adapter.  This is
/// only a generated Rust symbol name; it is not a persisted identity or
/// runtime protocol value.  Hashing the complete canonical binding lets
/// multiple fields which carry the same item/error pair safely share one
/// registry while keeping distinct pairs collision-resistant.
fn stream_adapter_suffix(binding: &RustValueBinding) -> String {
    let key = format!("{:?}|{:?}", binding.rust_type, binding.conversion);
    let mut hash = 0xcbf29ce484222325u64;
    for byte in key.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("nested_{hash:016x}")
}

fn stream_adapter_type_suffix(binding: &RustValueBinding) -> String {
    let suffix = stream_adapter_suffix(binding);
    let hash = suffix
        .strip_prefix("nested_")
        .expect("stream adapter suffix always starts with nested_");
    format!("Nested{hash}")
}

