//! Source renderer for the programmatic wasm engine.
//!
//! The renderer intentionally consumes the already-normalized Rust bridge
//! plan.  It emits the package-local typed adapters that wasm-bindgen's
//! in-process expansion consumes, followed by the real expansion tokens
//! (including descriptors and raw ABI shims).  There is no filesystem read,
//! manifest, sidecar, or external `wasm-bindgen` process in this module.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use anyhow::{anyhow, Result};
use proc_macro2::{Ident, Span, TokenStream};
use quote::quote;
use uniffi_js_abi::TypeId;
use uniffi_js_engine_schema::{
    ConversionRecipe, EngineKind, RustCallTarget, RustCarrier, RustNamedTypeKind,
    RustOperationPlan, RustType, RustValueBinding, RustVariantPayload,
};

use crate::frontend::NormalizedPackage;

use super::{
    rust_call_argument, rust_ident, rust_path, syn_type, wasm_operation_plan, wasm_resource_hooks,
};

/// Render one complete generated Wasm host source file.
pub(crate) fn render(
    package: &NormalizedPackage,
    context: wasm_bindgen_uniffi_engine::ExpansionContext,
) -> Result<String> {
    let plan = engine_plan(package)?;

    let operations = plan
        .expand(context.clone())
        .map_err(|error| anyhow!("expanding wasm operation descriptors: {error}"))?;
    let resource_hooks = plan
        .expand_resource_hooks(context)
        .map_err(|error| anyhow!("expanding wasm resource descriptors: {error}"))?;

    let mut source = String::new();
    write_prelude(&mut source);
    write_registry(&mut source);
    write_temporal_helpers(&mut source);
    source.push_str(&render_callback_helpers(package)?);
    source.push_str(&render_named_helpers(package)?);
    source.push_str(&render_stream_helpers(package)?);
    source.push_str(&render_operations(package)?);
    source.push_str("\n// wasm-bindgen operation descriptors and ABI shims\n");
    for operation in operations {
        writeln!(source, "{}", operation.tokens).unwrap();
    }
    source.push_str("\n// wasm-bindgen resource descriptors and ABI shims\n");
    for hook in resource_hooks {
        writeln!(source, "{}", hook.tokens).unwrap();
    }
    Ok(source)
}

fn engine_plan(package: &NormalizedPackage) -> Result<wasm_bindgen_uniffi_engine::WasmEnginePlan> {
    let operations = package.rust.engines[&EngineKind::WasmBindgen]
        .operations
        .iter()
        .map(|operation| wasm_operation_plan(package, operation))
        .collect::<Result<Vec<_>>>()?;
    wasm_bindgen_uniffi_engine::WasmEnginePlan::build_with_resource_hooks(
        wasm_bindgen_uniffi_engine::ClosePolicy {
            grace_ms: package.bridge.close_policy().grace_ms,
            on_deadline: wasm_bindgen_uniffi_engine::DeadlineAction::Detach,
        },
        operations,
        wasm_resource_hooks()?,
    )
    .map_err(|error| anyhow!("Wasm engine plan: {error}"))
}

/// Run the pinned wasm-bindgen post-link engine without invoking the external
/// CLI.  The returned output owns the generated loader and rewritten wasm
/// bytes; callers publish both as one package unit.
pub(crate) fn post_link(
    package: &NormalizedPackage,
    wasm_path: &std::path::Path,
    module_name: &str,
    target: wasm_bindgen_uniffi_engine::PostLinkTarget,
) -> Result<wasm_bindgen_uniffi_engine::PostLinkOutput> {
    let plan = engine_plan(package)?;
    plan.post_link(wasm_path, module_name, target)
        .run()
        .map_err(|error| anyhow!("wasm post-link: {error}"))
}

fn write_prelude(source: &mut String) {
    source.push_str(
        r#"// AUTOGENERATED by uniffi_bindgen_javascript; do not edit by hand.
use wasm_bindgen::prelude::*;
use wasm_bindgen::JsCast;
use std::cell::{Cell, RefCell};
use std::collections::HashMap;

"#,
    );
}

fn write_registry(source: &mut String) {
    source.push_str(
        r#"thread_local! {
    static __UNIFFI_WASM_OBJECTS: RefCell<HashMap<u32, Box<dyn std::any::Any>>> =
        RefCell::new(HashMap::new());
    static __UNIFFI_WASM_NEXT_HANDLE: Cell<u32> = Cell::new(0);
    static __UNIFFI_WASM_NEXT_CALLBACK_INVOCATION: Cell<u32> = Cell::new(0);
    // The wasm-bindgen engine supplies a per-call host object for operations
    // which contain callbacks or foreign input streams.  Lowering is
    // recursive (records/containers may contain either value), so keeping a
    // short-lived copy in this cell avoids smuggling host parameters through
    // every generated conversion helper.  Callback proxies copy the host
    // before the cell is cleared.
    static __UNIFFI_WASM_CALL_HOST: RefCell<Option<JsValue>> = RefCell::new(None);
}

fn __uniffi_set_call_host(host: Option<JsValue>) {
    __UNIFFI_WASM_CALL_HOST.with(|slot| *slot.borrow_mut() = host);
}

fn __uniffi_call_host() -> Result<JsValue, JsValue> {
    __UNIFFI_WASM_CALL_HOST.with(|slot| {
        slot.borrow()
            .as_ref()
            .cloned()
            .ok_or_else(|| JsValue::from_str("wasm callback/input-stream host is unavailable"))
    })
}

fn __uniffi_next_callback_invocation() -> u32 {
    __UNIFFI_WASM_NEXT_CALLBACK_INVOCATION.with(|next| {
        let current = next.get();
        let following = current
            .checked_add(1)
            .expect("wasm callback invocation ID overflow");
        next.set(following);
        current
    })
}

fn __uniffi_store_object<T: 'static>(value: T) -> u32 {
    let id = __UNIFFI_WASM_NEXT_HANDLE.with(|next| {
        let current = next.get().checked_add(1).expect("wasm object handle overflow");
        next.set(current);
        current
    });
    __UNIFFI_WASM_OBJECTS.with(|objects| {
        objects.borrow_mut().insert(id, Box::new(value));
    });
    id
}

fn __uniffi_take_object<T: Clone + 'static>(handle: u32, owned: bool) -> Result<T, JsValue> {
    __UNIFFI_WASM_OBJECTS.with(|objects| {
        let mut objects = objects.borrow_mut();
        if owned {
            let value = objects
                .remove(&handle)
                .ok_or_else(|| JsValue::from_str("invalid or already-consumed wasm object handle"))?;
            value
                .downcast::<T>()
                .map(|value| *value)
                .map_err(|_| JsValue::from_str("wasm object handle has an unexpected type"))
        } else {
            objects
                .get(&handle)
                .and_then(|value| value.downcast_ref::<T>())
                .cloned()
                .ok_or_else(|| JsValue::from_str("invalid wasm object handle"))
        }
    })
}

#[doc(hidden)]
fn __uniffi_wasm_release_object_impl(handle: u32) -> Result<(), JsValue> {
    __UNIFFI_WASM_OBJECTS.with(|objects| {
        objects.borrow_mut().remove(&handle);
    });
    Ok(())
}

"#,
    );
}

fn write_temporal_helpers(source: &mut String) {
    source.push_str(
        r#"fn __uniffi_lower_timestamp(value: JsValue) -> Result<std::time::SystemTime, JsValue> {
    let date: js_sys::Date = value.dyn_into().map_err(|_| JsValue::from_str("expected Date"))?;
    let millis = date.get_time();
    if !millis.is_finite() || millis.abs() > 8.64e15 {
        return Err(JsValue::from_str("timestamp exceeds JS Date range"));
    }
    let millis = millis.trunc() as i64;
    if millis >= 0 {
        std::time::UNIX_EPOCH
            .checked_add(std::time::Duration::from_millis(millis as u64))
            .ok_or_else(|| JsValue::from_str("timestamp exceeds JS Date range"))
    } else {
        std::time::UNIX_EPOCH
            .checked_sub(std::time::Duration::from_millis((-millis) as u64))
            .ok_or_else(|| JsValue::from_str("timestamp exceeds JS Date range"))
    }
}

fn __uniffi_lift_timestamp(value: std::time::SystemTime) -> Result<JsValue, JsValue> {
    let millis = match value.duration_since(std::time::UNIX_EPOCH) {
        Ok(delta) => delta.as_secs() as f64 * 1000.0 + delta.subsec_nanos() as f64 / 1_000_000.0,
        Err(error) => {
            let delta = error.duration();
            -(delta.as_secs() as f64 * 1000.0 + delta.subsec_nanos() as f64 / 1_000_000.0)
        }
    };
    if !millis.is_finite() || millis.abs() > 8.64e15 {
        return Err(JsValue::from_str("timestamp exceeds JS Date range"));
    }
    Ok(js_sys::Date::new(&JsValue::from_f64(millis)).into())
}

fn __uniffi_lower_duration(value: JsValue) -> Result<std::time::Duration, JsValue> {
    let millis = value.as_f64().ok_or_else(|| JsValue::from_str("expected duration milliseconds"))?;
    if !millis.is_finite() || millis < 0.0 {
        return Err(JsValue::from_str("duration must be a non-negative finite number"));
    }
    let seconds = (millis / 1000.0).trunc() as u64;
    let nanos = ((millis % 1000.0) * 1_000_000.0).round() as u32;
    std::time::Duration::new(seconds, nanos)
        .checked_add(std::time::Duration::ZERO)
        .ok_or_else(|| JsValue::from_str("duration overflow"))
}

fn __uniffi_lift_duration(value: std::time::Duration) -> Result<JsValue, JsValue> {
    Ok(JsValue::from_f64(value.as_secs() as f64 * 1000.0 + value.subsec_nanos() as f64 / 1_000_000.0))
}

"#,
    );
}

fn core_type(package: &NormalizedPackage, binding: &RustValueBinding) -> Result<syn::Type> {
    match &binding.conversion {
        ConversionRecipe::Object(id) => super::object_core_type(package, *id),
        ConversionRecipe::Optional(inner) => {
            let inner = nested_binding(binding, inner, RustType::Unit);
            let ty = core_type(package, &inner)?;
            Ok(syn::parse_quote!(Option<#ty>))
        }
        ConversionRecipe::Sequence(inner) => {
            let inner = nested_binding(binding, inner, RustType::Unit);
            let ty = core_type(package, &inner)?;
            Ok(syn::parse_quote!(Vec<#ty>))
        }
        ConversionRecipe::Set(inner) => {
            let inner = nested_binding(binding, inner, RustType::Unit);
            let ty = core_type(package, &inner)?;
            Ok(syn::parse_quote!(::std::collections::HashSet<#ty>))
        }
        ConversionRecipe::Map(key, value) => {
            let (key_binding, value_binding) = map_bindings(binding, key, value);
            let key = core_type(package, &key_binding)?;
            let value = core_type(package, &value_binding)?;
            Ok(syn::parse_quote!(::std::collections::HashMap<#key, #value>))
        }
        ConversionRecipe::Callback(id) => {
            let named = package
                .rust
                .named_type(TypeId::new(id.index()))
                .ok_or_else(|| anyhow!("unknown callback type id {}", id.index()))?;
            let path = rust_path(&named.rust_path)?;
            Ok(syn::parse_quote!(::std::sync::Arc<dyn #path>))
        }
        // The canonical Rust stream binding carries both item and error types
        // (plus sendability) even when a stream is nested in a container or
        // named payload.  Render that exact pair instead of inventing a
        // JsValue error placeholder; direct operation slots still use their
        // resource group's equivalent item/error bindings.
        ConversionRecipe::InputStream {
            item: item_conversion,
            error: error_conversion,
        } => {
            let RustType::InputStream { item, error, .. } = &binding.rust_type else {
                return Err(anyhow!(
                    "input stream binding has no canonical item/error types"
                ));
            };
            let item = core_type(
                package,
                &RustValueBinding {
                    rust_type: (**item).clone(),
                    carrier: RustCarrier::LocalAdapter,
                    conversion: (**item_conversion).clone(),
                },
            )?;
            let error = core_type(
                package,
                &RustValueBinding {
                    rust_type: (**error).clone(),
                    carrier: RustCarrier::LocalAdapter,
                    conversion: (**error_conversion).clone(),
                },
            )?;
            Ok(syn::parse_quote!(::uniffi::UniFfiInputStream<#item, #error>))
        }
        ConversionRecipe::OutputStream {
            item: item_conversion,
            error: error_conversion,
        } => {
            let RustType::Stream { item, error, .. } = &binding.rust_type else {
                return Err(anyhow!(
                    "output stream binding has no canonical item/error types"
                ));
            };
            let item = core_type(
                package,
                &RustValueBinding {
                    rust_type: (**item).clone(),
                    carrier: RustCarrier::LocalAdapter,
                    conversion: (**item_conversion).clone(),
                },
            )?;
            let error = core_type(
                package,
                &RustValueBinding {
                    rust_type: (**error).clone(),
                    carrier: RustCarrier::LocalAdapter,
                    conversion: (**error_conversion).clone(),
                },
            )?;
            Ok(syn::parse_quote!(::uniffi::UniFfiStream<#item, #error>))
        }
        ConversionRecipe::Custom(_, _) => syn_type(&binding.rust_type, "wasm"),
        ConversionRecipe::StreamStep { item, error } => {
            let item_binding = nested_binding(binding, item, RustType::Unit);
            let error_binding = nested_binding(binding, error, RustType::Unit);
            let item = core_type(package, &item_binding)?;
            let error = core_type(package, &error_binding)?;
            Ok(syn::parse_quote!(::uniffi::UniFfiStreamStep<#item, #error>))
        }
        _ => syn_type(&binding.rust_type, "wasm"),
    }
}

fn declared_error_binding(package: &NormalizedPackage, id: TypeId) -> Result<RustValueBinding> {
    let named = package
        .rust
        .named_type(id)
        .ok_or_else(|| anyhow!("missing declared error type {}", id.index()))?;
    if !matches!(named.kind, RustNamedTypeKind::Error { .. }) {
        return Err(anyhow!(
            "declared error type {} is not a Rust error",
            id.index()
        ));
    }
    Ok(RustValueBinding {
        rust_type: RustType::Path(named.rust_path.clone()),
        carrier: RustCarrier::LocalAdapter,
        conversion: ConversionRecipe::Error(id),
    })
}

fn nested_binding(
    parent: &RustValueBinding,
    conversion: &ConversionRecipe,
    fallback: RustType,
) -> RustValueBinding {
    let rust_type = match (&parent.rust_type, conversion) {
        (RustType::Option(inner), _) => (**inner).clone(),
        (RustType::Sequence(inner), _) => (**inner).clone(),
        (RustType::Set(inner), _) => (**inner).clone(),
        (RustType::Map(key, _), ConversionRecipe::Map(_, _)) => (**key).clone(),
        (RustType::Map(_, value), _) => (**value).clone(),
        (RustType::InputStream { item, .. }, ConversionRecipe::InputStream { .. }) => {
            (**item).clone()
        }
        (RustType::Stream { item, .. }, ConversionRecipe::OutputStream { .. }) => (**item).clone(),
        (RustType::StreamStep { item, .. }, ConversionRecipe::StreamStep { .. }) => {
            (**item).clone()
        }
        (RustType::Custom(inner), ConversionRecipe::Custom(_, _)) => (**inner).clone(),
        _ => fallback,
    };
    RustValueBinding {
        rust_type,
        carrier: parent.carrier,
        conversion: conversion.clone(),
    }
}

/// Return the canonical key/value bindings for a map conversion.  A map's
/// child conversions are indistinguishable by themselves (both may be
/// `Identity`), so selecting a child through `nested_binding` can accidentally
/// pick the value type for the key.  Keep the RustType::Map pair authoritative
/// and only use each child conversion for its corresponding side.
fn map_bindings(
    parent: &RustValueBinding,
    key: &ConversionRecipe,
    value: &ConversionRecipe,
) -> (RustValueBinding, RustValueBinding) {
    let (key_rust_type, value_rust_type) = match &parent.rust_type {
        RustType::Map(key_type, value_type) => {
            (key_type.as_ref().clone(), value_type.as_ref().clone())
        }
        _ => (RustType::Unit, RustType::Unit),
    };
    (
        RustValueBinding {
            rust_type: key_rust_type,
            carrier: parent.carrier,
            conversion: key.clone(),
        },
        RustValueBinding {
            rust_type: value_rust_type,
            carrier: parent.carrier,
            conversion: value.clone(),
        },
    )
}

fn wasm_param_type(binding: &RustValueBinding) -> TokenStream {
    match super::wasm_carrier(binding) {
        wasm_bindgen_uniffi_engine::WasmCarrier::Bool => quote!(bool),
        wasm_bindgen_uniffi_engine::WasmCarrier::I8 => quote!(i8),
        wasm_bindgen_uniffi_engine::WasmCarrier::U8 => quote!(u8),
        wasm_bindgen_uniffi_engine::WasmCarrier::I16 => quote!(i16),
        wasm_bindgen_uniffi_engine::WasmCarrier::U16 => quote!(u16),
        wasm_bindgen_uniffi_engine::WasmCarrier::I32 => quote!(i32),
        wasm_bindgen_uniffi_engine::WasmCarrier::U32
        | wasm_bindgen_uniffi_engine::WasmCarrier::OpaqueHandle => quote!(u32),
        wasm_bindgen_uniffi_engine::WasmCarrier::I64 => quote!(i64),
        wasm_bindgen_uniffi_engine::WasmCarrier::U64 => quote!(u64),
        wasm_bindgen_uniffi_engine::WasmCarrier::F32 => quote!(f32),
        wasm_bindgen_uniffi_engine::WasmCarrier::F64 => quote!(f64),
        wasm_bindgen_uniffi_engine::WasmCarrier::String => quote!(String),
        wasm_bindgen_uniffi_engine::WasmCarrier::Bytes => quote!(Vec<u8>),
        wasm_bindgen_uniffi_engine::WasmCarrier::JsValue => quote!(JsValue),
    }
}

