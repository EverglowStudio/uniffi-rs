use super::*;

fn def(kind: &str, name: &str, definition: &str) -> TypeDefLine {
    TypeDefLine {
        kind: kind.to_string(),
        name: name.to_string(),
        original_name: None,
        def: definition.to_string(),
        js_doc: None,
        js_mod: Some("__TOP_LEVEL_MODULE__".to_string()),
        extends: None,
    }
}

#[test]
fn package_entry_reexports_raw_types_without_duplicating_value_classes() {
    let defs = vec![
        def("interface", "RecordPayload", "value: number"),
        def("string_enum", "Status", "Ready = 'Ready'"),
        def("struct", "Worker", "constructor();"),
        def("fn", "run", "function run(value: RecordPayload): Status"),
    ];
    let exports = FacadeExports::from_type_defs(&defs).unwrap();

    let native = exports.render_native_facade("libfixture.so");
    assert!(
        native.contains("import type {\n  RecordPayload,\n  Status,\n} from \"libfixture.so\";\n")
    );
    assert!(
        native.contains("export type {\n  RecordPayload,\n  Status,\n} from \"libfixture.so\";\n")
    );

    let package = exports.render_package_index();
    assert!(package.starts_with(
        "// AUTOGENERATED by UniFFI (Harmony package entry).\n\
         export {\n  Worker,\n  run,\n} from \"./src/main/ets/native\";\n"
    ));
    assert!(package.ends_with(
        "export type {\n  RecordPayload,\n  Status,\n} from \"./src/main/ets/native\";\n"
    ));
    assert!(!package.contains("export type {\n  RecordPayload,\n  Status,\n  Worker,"));
}

#[test]
fn package_entry_reexports_public_harmony_stream_interfaces() {
    let streams = HarmonyStreamFacade {
        contracts: vec![HarmonyFacadeContract {
            schema_version: FACADE_CONTRACT_SCHEMA_VERSION,
            component: "fixture".to_string(),
            output_streams: vec![HarmonyOutputStreamContract {
                function: "events".to_string(),
                next_function: "eventsStreamNext".to_string(),
                cancel_function: "eventsStreamCancel".to_string(),
                stream_factory: "eventsStream".to_string(),
                events_factory: "eventsEvents".to_string(),
                pull_class: "EventsPullStream".to_string(),
                events_class: "EventsEventsStream".to_string(),
                next_type: "EventsStreamNext".to_string(),
                item_type: HarmonyTypeDescriptor::Number,
                error_type: HarmonyTypeDescriptor::String,
                arguments: Vec::new(),
            }],
            input_streams: Vec::new(),
        }],
        native_types: vec!["EventsStreamNext".to_string()],
        package_hidden_next_envelopes: Vec::new(),
        host_composite_identity: String::new(),
        component_identities: Vec::new(),
    };
    let exports = FacadeExports {
        callables: vec!["events".to_string()],
        callable_types: BTreeMap::from([("events".to_string(), "() => bigint".to_string())]),
        classes: Vec::new(),
        streams,
    };

    assert_eq!(
        exports.type_exports(),
        vec![
            "UniFfiInputFailureData",
            "UniFfiStream",
            "UniFfiStreamErrorData",
        ]
    );
    let package = exports.render_package_index();
    for name in [
        "UniFfiInputFailureData",
        "UniFfiStream",
        "UniFfiStreamErrorData",
    ] {
        assert!(
            package.contains(&format!("  {name},\n")),
            "missing package-root type export for {name}:\n{package}"
        );
    }
    for raw in [
        "events",
        "eventsStreamNext",
        "eventsStreamCancel",
        "EventsStreamNext",
    ] {
        assert!(
            !package.contains(&format!("  {raw},\n")),
            "package root must hide output raw `{raw}`:\n{package}"
        );
    }
    for class in ["EventsEventsStream", "EventsPullStream"] {
        assert_eq!(
            package.matches(&format!("  {class},\n")).count(),
            1,
            "stream classes must remain value exports and must not be duplicated"
        );
    }
}

#[test]
fn no_stream_package_uses_only_raw_type_exports() {
    let exports =
        FacadeExports::from_type_defs(&[def("interface", "RecordPayload", "value: number")])
            .unwrap();
    assert_eq!(exports.type_exports(), vec!["RecordPayload"]);
    let package = exports.render_package_index();
    assert!(!package.contains("UniFfiStream"));
    assert_eq!(package.matches("export type {").count(), 1);
}
