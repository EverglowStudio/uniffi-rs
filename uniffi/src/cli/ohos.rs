pub(crate) fn write_owned_tree_marker(
    root: &Utf8Path,
    marker_name: &str,
    owner: &str,
) -> Result<OwnedTreeSnapshot> {
    validate_marker_name(marker_name)?;
    let generation = new_generation_id();
    let entries = collect_owned_tree_entries(root, marker_name)?;
    let marker = serde_json::json!({
        "owner": owner,
        "schemaVersion": OWNER_SCHEMA_VERSION,
        "generation": generation,
        "entries": entries.iter().map(|(path, entry)| serde_json::json!({
            "path": path,
            "kind": entry.kind,
            "sha256": entry.sha256,
        })).collect::<Vec<_>>(),
    });
    let mut text = serde_json::to_string_pretty(&marker)?;
    text.push('\n');
    let marker_path = root.join(marker_name);
    let mut marker_file = OpenOptions::new()
        .create_new(true)
        .write(true)
        .open(&marker_path)
        .with_context(|| {
            format!("creating new {owner} ownership marker {marker_path}; an existing marker is never overwritten")
        })?;
    marker_file
        .write_all(text.as_bytes())
        .with_context(|| format!("writing {owner} ownership marker {marker_path}"))?;
    marker_file.sync_all()?;
    validate_owned_tree(root, marker_name, owner)
}

pub(crate) fn validate_owned_tree(
    root: &Utf8Path,
    marker_name: &str,
    owner: &str,
) -> Result<OwnedTreeSnapshot> {
    validate_marker_name(marker_name)?;
    let root_metadata =
        std::fs::symlink_metadata(root).with_context(|| format!("reading {owner} root {root}"))?;
    if root_metadata.file_type().is_symlink() || !root_metadata.is_dir() {
        bail!("{owner} root must be a real directory: {root}");
    }
    let marker_path = root.join(marker_name);
    let marker_metadata = std::fs::symlink_metadata(&marker_path)
        .with_context(|| format!("missing {owner} ownership marker {marker_path}"))?;
    if marker_metadata.file_type().is_symlink() || !marker_metadata.is_file() {
        bail!("{owner} ownership marker must be a regular file: {marker_path}");
    }
    ensure_file_has_single_link(&marker_metadata, &marker_path)?;
    let marker: Value = serde_json::from_slice(
        &std::fs::read(&marker_path)
            .with_context(|| format!("reading {owner} ownership marker {marker_path}"))?,
    )
    .with_context(|| format!("parsing {owner} ownership marker {marker_path}"))?;
    if marker.get("owner").and_then(Value::as_str) != Some(owner)
        || marker.get("schemaVersion").and_then(Value::as_u64) != Some(OWNER_SCHEMA_VERSION)
    {
        bail!("unsupported or damaged {owner} ownership marker: {marker_path}");
    }
    let generation = marker
        .get("generation")
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .context("ownership marker generation must be a non-empty string")?
        .to_string();
    let declared = marker
        .get("entries")
        .and_then(Value::as_array)
        .context("ownership marker entries must be an array")?;
    let mut entries = BTreeMap::new();
    for value in declared {
        let path = value
            .get("path")
            .and_then(Value::as_str)
            .context("ownership inventory path must be a string")?;
        validate_inventory_path(path, marker_name)?;
        let kind = value
            .get("kind")
            .and_then(Value::as_str)
            .filter(|kind| matches!(*kind, "file" | "directory"))
            .context("ownership inventory kind must be `file` or `directory`")?
            .to_string();
        let sha256 = value
            .get("sha256")
            .and_then(Value::as_str)
            .map(str::to_string);
        if (kind == "file") != sha256.is_some() {
            bail!("ownership inventory files require sha256 and directories must omit it: {path}");
        }
        if entries
            .insert(path.to_string(), OwnedTreeEntry { kind, sha256 })
            .is_some()
        {
            bail!("ownership inventory contains duplicate path: {path}");
        }
    }
    let actual = collect_owned_tree_entries(root, marker_name)?;
    if entries != actual {
        bail!("{owner} tree no longer matches its exact ownership inventory; refusing replacement");
    }
    Ok(OwnedTreeSnapshot {
        generation,
        entries,
    })
}

fn validate_marker_name(marker_name: &str) -> Result<()> {
    if marker_name.is_empty() || marker_name.contains(['/', '\\']) || marker_name == "." {
        bail!("invalid ownership marker file name `{marker_name}`");
    }
    Ok(())
}

fn validate_inventory_path(path: &str, marker_name: &str) -> Result<()> {
    let path = Utf8Path::new(path);
    if path.as_str().is_empty()
        || path.is_absolute()
        || path == Utf8Path::new(marker_name)
        || path
            .components()
            .any(|component| matches!(component.as_str(), "" | "." | ".."))
    {
        bail!("unsafe ownership inventory path `{path}`");
    }
    Ok(())
}

fn collect_owned_tree_entries(
    root: &Utf8Path,
    marker_name: &str,
) -> Result<BTreeMap<String, OwnedTreeEntry>> {
    fn visit(
        root: &Utf8Path,
        current: &Utf8Path,
        marker_name: &str,
        entries: &mut BTreeMap<String, OwnedTreeEntry>,
    ) -> Result<()> {
        for entry in std::fs::read_dir(current)
            .with_context(|| format!("reading generator-owned tree {current}"))?
        {
            let entry = entry?;
            let path = Utf8PathBuf::from_path_buf(entry.path()).map_err(|path| {
                anyhow::anyhow!("generator-owned path is not UTF-8: {}", path.display())
            })?;
            let relative = path
                .strip_prefix(root)
                .with_context(|| format!("owned path escaped root: {path}"))?;
            if relative == Utf8Path::new(marker_name) {
                continue;
            }
            let relative_text = relative.as_str().replace('\\', "/");
            validate_inventory_path(&relative_text, marker_name)?;
            let metadata = std::fs::symlink_metadata(&path)?;
            if metadata.file_type().is_symlink() {
                bail!("generator-owned tree contains a symlink: {relative_text}");
            }
            let owned = if metadata.is_dir() {
                OwnedTreeEntry {
                    kind: "directory".into(),
                    sha256: None,
                }
            } else if metadata.is_file() {
                ensure_file_has_single_link(&metadata, &path)?;
                OwnedTreeEntry {
                    kind: "file".into(),
                    sha256: Some(sha256_file(&path)?),
                }
            } else {
                bail!("generator-owned tree contains a non-regular entry: {relative_text}");
            };
            if entries.insert(relative_text.clone(), owned).is_some() {
                bail!("generator-owned tree contains duplicate path: {relative_text}");
            }
            if metadata.is_dir() {
                visit(root, &path, marker_name, entries)?;
            }
        }
        Ok(())
    }

    let mut entries = BTreeMap::new();
    visit(root, root, marker_name, &mut entries)?;
    Ok(entries)
}

fn sha256_file(path: &Utf8Path) -> Result<String> {
    let mut file = std::fs::File::open(path)
        .with_context(|| format!("opening generator-owned file {path}"))?;
    let mut digest = Sha256::new();
    let mut buffer = [0u8; 64 * 1024];
    loop {
        let count = file
            .read(&mut buffer)
            .with_context(|| format!("reading generator-owned file {path}"))?;
        if count == 0 {
            break;
        }
        digest.update(&buffer[..count]);
    }
    Ok(format!("{:x}", digest.finalize()))
}

#[cfg(unix)]
fn ensure_file_has_single_link(metadata: &std::fs::Metadata, path: &Utf8Path) -> Result<()> {
    use std::os::unix::fs::MetadataExt;
    if metadata.nlink() != 1 {
        bail!("generator-owned file must not be a hardlink: {path}");
    }
    Ok(())
}

#[cfg(windows)]
fn ensure_file_has_single_link(_metadata: &std::fs::Metadata, path: &Utf8Path) -> Result<()> {
    let info = windows_file_information(path.as_std_path())?;
    if info.number_of_links != 1 {
        bail!("generator-owned file must not be a hardlink: {path}");
    }
    Ok(())
}

#[cfg(not(any(unix, windows)))]
fn ensure_file_has_single_link(_metadata: &std::fs::Metadata, path: &Utf8Path) -> Result<()> {
    bail!("hardlink validation is unsupported on this host; refusing generator-owned file {path}")
}

fn new_generation_id() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_nanos())
        .unwrap_or_default();
    let counter = GENERATION_COUNTER.fetch_add(1, Ordering::Relaxed);
    format!("{}-{nanos}-{counter}", std::process::id())
}

