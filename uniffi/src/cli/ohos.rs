    #[test]
    fn generates_har_with_package_root_and_no_absolute_paths() {
        let root = temp_test_dir("uniffi-ohos-har");
        let package_dir = root.join("package");
        std::fs::create_dir_all(package_dir.join("src/main")).unwrap();
        std::fs::create_dir_all(package_dir.join("libs/arm64-v8a")).unwrap();
        std::fs::write(
            package_dir.join("oh-package.json5"),
            render_oh_package_json5("@scope/demo", "0.0.1"),
        )
        .unwrap();
        std::fs::write(package_dir.join("index.ets"), render_index_ets("demo_ohos")).unwrap();
        std::fs::write(
            package_dir.join("src/main/module.json5"),
            render_module_json5("@scope/demo"),
        )
        .unwrap();
        std::fs::write(package_dir.join("libs/index.d.ts"), "export {}\n").unwrap();
        std::fs::write(package_dir.join("libs/arm64-v8a/libdemo_ohos.so"), "fake").unwrap();

        let har = root.join("demo.har");
        generate_har_archive(&har, &package_dir).unwrap();

        let file = std::fs::File::open(&har).unwrap();
        let decoder = flate2::read::GzDecoder::new(file);
        let mut archive = tar::Archive::new(decoder);
        let mut saw_required = false;
        for entry in archive.entries().unwrap() {
            let entry = entry.unwrap();
            let path = entry.path().unwrap().to_string_lossy().to_string();
            assert!(!path.starts_with('/'), "entry must not be absolute: {path}");
            assert!(
                !path.contains(":\\"),
                "entry must not include windows absolute path: {path}"
            );
            assert!(
                path == "package" || path.starts_with("package/"),
                "entry must be rooted at package/: {path}"
            );
            if path == "package/oh-package.json5" {
                saw_required = true;
            }
        }
        assert!(saw_required, "HAR must contain package/oh-package.json5");
        std::fs::remove_dir_all(root).ok();
    }

